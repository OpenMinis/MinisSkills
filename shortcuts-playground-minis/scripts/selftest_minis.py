def run(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(args, text=True, capture_output=True)


def fail(stage: str, stdout: str, stderr: str) -> int:
    print(json.dumps({"ok": False, "stage": stage, "stdout": stdout, "stderr": stderr}, ensure_ascii=False, indent=2))
    return 1


def main() -> int:
    DRAFTS.mkdir(parents=True, exist_ok=True)
    TEST_XML.write_text(XML, encoding="utf-8")

    validate = run(sys.executable, str(ROOT / "scripts/validate_shortcut.py"), str(TEST_XML))
    if validate.returncode != 0:
        return fail("validate_minimal_draft", validate.stdout, validate.stderr)

    cfg = run(sys.executable, str(ROOT / "scripts/sign_shortcut.py"), "--show-config")
    if "--sign" not in sys.argv:
        print(json.dumps({"ok": True, "signed": False, "note": "validation only; pass --sign to also test the configured signing backend",
                          "signing_config": json.loads(cfg.stdout or "{}")}, ensure_ascii=False))
        return 0

    sign = run(sys.executable, str(ROOT / "scripts/sign_shortcut.py"), str(TEST_XML), "--name", "Selftest Hello")
    if sign.returncode != 0:
        return fail("sign_minimal_draft", sign.stdout, sign.stderr)

    print(sign.stdout)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
