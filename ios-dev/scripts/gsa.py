"""gsa.py — GrandSlam (Apple ID) login: init → complete (SRP) → (2FA) → apptokens (obtain an Xcode token).
Corresponds to xtool's GrandSlamAuthenticateOperation / TwoFactor / FetchAppTokens.
Security rules: the password is only read from the APPLE_PASSWORD environment variable; never logged, never written to disk, never on the command line.
"""
import hashlib, hmac, os, plistlib, sys, json
import urllib.request, urllib.error
import anisette as A
from srp_client import SRPClient
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

XCODE_APP = "com.apple.gs.xcode.auth"
# Since 2026-10-12 Apple rejects "Anisette generated by Android but claiming to be macOS" (-80045).
# GSA endpoints must use the Windows identity (see Dadoum/anisette-v3-server#61).
GSA_CLIENT_INFO = "<PC> <Windows;6.2(0,0);9200> <com.apple.AuthKit/1 (com.apple.akd/1.0)>"
XCODE_VERSION = "26.5 (17F42)"

class GSAError(Exception):
    def __init__(self, code, msg): super().__init__(f"{msg} ({code})"); self.code = code

class Session:
    def __init__(self):
        self.anis, self.ci = A.get_headers()
        self.uid = self.anis["X-Mme-Device-Id"]
        self.urls = A.lookup(self.ci, self.uid)

    # ---------- low level ----------
    def _client_data(self):
        d = {"bootstrap": True, "icscrec": True, "pbe": False, "prkgen": True, "svct": "iCloud", "loc": "en_US"}
        # xtool's fixed device information on non-macOS (ROM/MLB/serial), GSA checks that these fields are present
        d.update({"X-Apple-I-ROM": "94f6a300e9a0", "X-Apple-I-MLB": "C02520301W0GF2D1U",
                  "X-Apple-I-SRL-NO": "C02PQKRJG8WP"})
        d.update(self.anis)
        return d

    def _op(self, operation, username, **params):
        """GrandSlam 'operation' request (init/complete/apptokens), POST plist."""
        req = {"o": operation, "u": username, "cpd": self._client_data()}
        req.update(params)
        body = plistlib.dumps({"Header": {"Version": "1.0.1"}, "Request": req}, fmt=plistlib.FMT_XML)
        h = {"Content-Type": "text/x-xml-plist", "Accept": "*/*", "User-Agent": self.ci["user_agent"],
             "X-MMe-Client-Info": GSA_CLIENT_INFO}
        b, _ = A.http(self.urls["gsService"], body, h, A.apple_ctx())
        resp = plistlib.loads(b)["Response"]
        st = resp.get("Status", {})
        if st.get("ec", 0) != 0: raise GSAError(st["ec"], st.get("em", ""))
        return resp

    def _2fa_headers(self, login):
        ident = (login["adsid"] + ":" + login["GsIdmsToken"]).encode()
        import base64
        h = {"Accept": "application/x-buddyml", "Content-Type": "application/x-plist",
             "User-Agent": self.ci["user_agent"], "X-MMe-Client-Info": self.ci["client_info"],  # the 2FA endpoint wants Mac, Windows gets 403
             "X-Apple-App-Info": XCODE_APP, "X-Xcode-Version": XCODE_VERSION,
             "X-Apple-Identity-Token": base64.b64encode(ident).decode()}
        h.update(self.anis)
        return h

    # ---------- login ----------
    def authenticate(self, username, password, code_provider, _retry=False):
        import time, urllib.error
        for attempt in range(4):
            try:
                return self._authenticate(username, password, code_provider, _retry)
            except urllib.error.HTTPError as e:      # GSA occasionally returns 503: redo the whole SRP after a few seconds
                if e.code not in (502, 503) or attempt == 3: raise
                time.sleep(8)
            except (urllib.error.URLError, OSError):
                if attempt == 3: raise
                time.sleep(4)

    def _authenticate(self, username, password, code_provider, _retry=False):
        username = username.lower()   # GSA requires the SRP username to be lowercase
        srp = SRPClient()
        protos = ["s2k", "s2k_fo"]
        srp.add_str(",".join(protos)); srp.add_str("|")
        init = self._op("init", username, ps=protos, A2k=srp.public_key())
        srp.add_str("|"); srp.add_str(init["sp"])
        m1 = srp.process_challenge(username, password, init["s"], init["i"], init["sp"] == "s2k_fo", init["B"])
        comp = self._op("complete", username, c=init["c"], M1=m1)
        srp.add_str("|"); srp.add_data(comp["spd"]); srp.add_str("|")
        if comp.get("sc"): srp.add_data(comp["sc"])
        srp.add_str("|")
        if not (srp.verify_hamk(comp["M2"]) and srp.verify_np(comp["np"])):
            raise GSAError(-1, "server verification failed (SRP mismatch, possibly a wrong password or an implementation difference)")
        raw = srp.decrypt_cbc(comp["spd"])
        if not raw.lstrip().startswith(b"<?xml") and b"<plist" not in raw[:200]:
            raw = b'<?xml version="1.0" encoding="UTF-8"?><plist version="1.0">' + raw + b"</plist>"   # the server returned a bare <dict>
        spd = plistlib.loads(raw)
        if spd.get("status-code") == 409 or "au" in spd and spd.get("status-code") == 409:
            if _retry: raise GSAError(-2, "2FA is still required after the second verification")
            self._two_factor(spd, code_provider)
            return self._authenticate(username, password, code_provider, _retry=True)
        return spd   # contains adsid / GsIdmsToken / sk / c

    # ---------- 2FA ----------
    def _gsa_get(self, url, login, extra=None, post=None):
        h = self._2fa_headers(login)
        if extra: h.update(extra)
        data = plistlib.dumps(post, fmt=plistlib.FMT_XML) if post is not None else None
        try:
            b, _ = A.http(url, data, h, A.apple_ctx()); return b
        except urllib.error.HTTPError as e:
            raise GSAError(e.code, f"HTTP {e.code}: {e.read()[:200]!r}")

    @staticmethod
    def _check_validate(body):
        """validate returns HTTP 200 even on failure, the error code is inside the plist body and must be parsed."""
        try: d = plistlib.loads(body)
        except Exception: return          # not a plist (the buddyml success page), treat as success
        if isinstance(d, dict) and d.get("ec", 0) != 0:
            raise GSAError(d["ec"], d.get("em", ""))

    def _try_trusted_device(self, login):
        try:
            self._gsa_get(self.urls["trustedDeviceSecondaryAuth"], login); return True
        except GSAError:
            return False

    def _two_factor(self, login, code_provider):
        """Branching mirrors xtool's GrandSlamTwoFactorAuthenticateOperation:
        secondaryAuth            -> SMS (phone/put sends the code, phone/securitycode verifies it)
        trustedDeviceSecondaryAuth -> trusted device push, verified with validateCode
        None                      -> Apple already sent a code automatically, verified with validateCode
        (previously secondaryAuth was mistaken for a trusted device and SMS codes were verified with validateCode, which produced -21669)"""
        mode = login.get("url")
        self.last_2fa_mode = mode
        if mode == "secondaryAuth":
            pid = "1"   # xtool also hardcodes "1" (TODO: parse the phone number list)
            self._gsa_get("https://gsa.apple.com/auth/verify/phone/put?mode=sms", login,
                          post={"serverInfo": {"phone.id": pid, "phoneNumber.id": pid}})
            code = code_provider("SMS verification code")
            self._check_validate(self._gsa_get(
                "https://gsa.apple.com/auth/verify/phone/securitycode?referrer=/auth/verify/phone/put",
                login, post={"securityCode.code": code,
                             "serverInfo": {"mode": "sms", "phoneNumber.id": pid}}))
        elif mode == "trustedDeviceSecondaryAuth":
            self._gsa_get(self.urls["trustedDeviceSecondaryAuth"], login)
            code = code_provider("6-digit verification code shown on the trusted device")
            self._check_validate(self._gsa_get(self.urls["validateCode"], login, extra={"security-code": code}))
        else:
            code = code_provider("verification code (Apple already sent it automatically)")
            self._check_validate(self._gsa_get(self.urls["validateCode"], login, extra={"security-code": code}))

    # ---------- fetch the Xcode token ----------
    @staticmethod
    def _loads_plist_lenient(pt):
        """The server sometimes returns a bare <dict> (no plist header), even with leading whitespace/BOM; try progressively."""
        pt = pt.lstrip(b"\xef\xbb\xbf \r\n\t\x00")
        tries = [pt]
        if b"<plist" not in pt[:300]:
            tries.append(b'<?xml version="1.0" encoding="UTF-8"?><plist version="1.0">' + pt + b"</plist>")
        for t in tries:
            try: return plistlib.loads(t)
            except Exception: pass
        return None

    def fetch_xcode_token(self, login):
        sk, adsid = login["sk"], login["adsid"]
        h = hmac.new(sk, digestmod=hashlib.sha256)
        h.update(b"apptokens"); h.update(adsid.encode()); h.update(XCODE_APP.encode())
        r = self._op("apptokens", adsid, app=[XCODE_APP], c=login["c"], t=login["GsIdmsToken"], checksum=h.digest())
        # First check whether the server reported an error directly (ec/em in Status), then decrypt
        st = r.get("Status") or {}
        if isinstance(st, dict) and st.get("ec", 0) != 0:
            raise GSAError(st["ec"], st.get("em", "apptokens failed"))
        et = r["et"]
        aad, iv, tag = et[:3], et[3:19], et[-16:]
        pt = AESGCM(sk).decrypt(iv, et[19:-16] + tag, aad)
        d = self._loads_plist_lenient(pt)
        if d is None:                                   # still unparsable: dump the raw bytes to disk (mode 600), do not print them
            dbg = os.path.expanduser("~/.ios-signer/apptokens_raw.bin")
            open(dbg, "wb").write(pt); os.chmod(dbg, 0o600)
            raise GSAError(-3, f"apptokens plaintext is not a plist ({len(pt)} bytes total, header {pt[:12]!r}), written to {dbg}")
        t = (d.get("t") or {}).get(XCODE_APP)
        if not t:
            raise GSAError(-4, f"apptokens has no {XCODE_APP}; keys: {sorted(d.keys())} / t keys: {sorted((d.get('t') or {}).keys())}")
        return {"adsid": adsid, "token": t["token"], "expiry_ms": t["expiry"]}

def prompt_code(what):
    """Non-interactive environment: write a request marker, then poll for ~/.ios-signer/code.txt (written by the caller with the verification code)."""
    import time
    cp = os.path.expanduser("~/.ios-signer/code.txt"); rq = os.path.expanduser("~/.ios-signer/need_code")
    if os.path.exists(cp): os.remove(cp)
    open(rq, "w").write(what)
    print(f"\n📱 NEED_CODE: {what}", file=sys.stderr, flush=True)
    for _ in range(300):
        if os.path.exists(cp):
            c = open(cp).read().strip(); os.remove(cp); os.remove(rq); return c
        time.sleep(1)
    raise GSAError(-3, "timed out waiting for the verification code")

def _save_session(login):
    """The login session (contains sensitive values such as sk) is only written locally to ~/.ios-signer/session.json, mode 600, and never printed."""
    import base64
    def enc(v): return {"__b64__": base64.b64encode(v).decode()} if isinstance(v, (bytes, bytearray)) else v
    d = {k: enc(v) for k, v in login.items()}
    p = os.path.expanduser("~/.ios-signer/session.json")
    json.dump(d, open(p, "w")); os.chmod(p, 0o600); return p

def _load_session():
    import base64
    d = json.load(open(os.path.expanduser("~/.ios-signer/session.json")))
    return {k: (base64.b64decode(v["__b64__"]) if isinstance(v, dict) and "__b64__" in v else v) for k, v in d.items()}

if __name__ == "__main__":
    user = os.environ.get("APPLE_ID"); pw = os.environ.get("APPLE_PASSWORD")
    s = Session()
    os.makedirs(os.path.expanduser("~/.ios-signer"), exist_ok=True)
    if "--reuse" in sys.argv:                         # reuse the session already on disk, so no SMS is triggered
        login = _load_session(); print("♻️  reusing the saved session, adsid =", login["adsid"][:6] + "…", file=sys.stderr)
    else:
        if not user or not pw: sys.exit("Please set the APPLE_ID and APPLE_PASSWORD environment variables first")
        print("✅ Anisette ready, starting SRP login…", file=sys.stderr)
        login = s.authenticate(user, pw, prompt_code)
        print("✅ login succeeded, adsid =", login["adsid"][:6] + "…", "| session saved:", _save_session(login), file=sys.stderr)
    tok = s.fetch_xcode_token(login)
    p = os.path.expanduser("~/.ios-signer/xcode_token.json")
    json.dump(tok, open(p, "w")); os.chmod(p, 0o600)
    print(f"✅ obtained the Xcode token (expires {tok['expiry_ms']}), saved to {p}", file=sys.stderr)
